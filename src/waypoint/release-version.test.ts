import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, test } from "vitest";
import {
  assertConsistentVersions,
  compareSemver,
  parseStrictSemver,
  readAllVersions,
  resolveNextVersion,
  updateAllVersions,
} from "../../scripts/lib/release-version.mjs";

const tempDirs: string[] = [];

function createFixtureRepo(version = "0.1.0"): string {
  const dir = mkdtempSync(join(tmpdir(), "waypoint-release-ver-"));
  tempDirs.push(dir);
  mkdirSync(join(dir, "src-tauri"), { recursive: true });

  writeFileSync(
    join(dir, "package.json"),
    `${JSON.stringify({ name: "waypoint", version, private: true }, null, 2)}\n`,
    "utf8",
  );
  writeFileSync(
    join(dir, "package-lock.json"),
    `${JSON.stringify(
      {
        name: "waypoint",
        version,
        lockfileVersion: 3,
        packages: {
          "": { name: "waypoint", version },
          "node_modules/vite": { version: "8.3.8" },
        },
      },
      null,
      2,
    )}\n`,
    "utf8",
  );
  writeFileSync(
    join(dir, "src-tauri/tauri.conf.json"),
    `${JSON.stringify({ productName: "Waypoint", version }, null, 2)}\n`,
    "utf8",
  );
  writeFileSync(
    join(dir, "src-tauri/Cargo.toml"),
    [
      "[package]",
      'name = "waypoint"',
      `version = "${version}"`,
      'edition = "2021"',
      "",
      "[dependencies]",
      'tauri = { version = "2", features = [] }',
      "",
    ].join("\n"),
    "utf8",
  );
  writeFileSync(
    join(dir, "src-tauri/Cargo.lock"),
    [
      "# This file is automatically @generated by Cargo.",
      "version = 4",
      "",
      "[[package]]",
      'name = "serde"',
      'version = "1.0.200"',
      "",
      "[[package]]",
      'name = "waypoint"',
      `version = "${version}"`,
      'dependencies = ["serde"]',
      "",
      "[[package]]",
      'name = "zlib"',
      'version = "0.1.0"',
      "",
    ].join("\n"),
    "utf8",
  );

  return dir;
}

afterEach(() => {
  while (tempDirs.length > 0) {
    const dir = tempDirs.pop();
    if (dir) {
      rmSync(dir, { recursive: true, force: true });
    }
  }
});

describe("release-version helpers", () => {
  test("parses strict semver and rejects leading zeros or pre-release suffixes", () => {
    expect(parseStrictSemver("v1.2.3")).toEqual({
      version: "1.2.3",
      major: 1,
      minor: 2,
      patch: 3,
    });
    expect(parseStrictSemver("0.10.0").version).toBe("0.10.0");
    expect(() => parseStrictSemver("01.0.0")).toThrow();
    expect(() => parseStrictSemver("1.2.3-rc.1")).toThrow();
    expect(() => parseStrictSemver("1.2")).toThrow();
  });

  test("computes bump keywords and rejects equal or lower explicit versions", () => {
    expect(compareSemver("0.2.0", "0.1.9")).toBeGreaterThan(0);
    expect(resolveNextVersion("0.1.0", "patch")).toBe("0.1.1");
    expect(resolveNextVersion("0.1.9", "minor")).toBe("0.2.0");
    expect(resolveNextVersion("0.9.5", "major")).toBe("1.0.0");
    expect(resolveNextVersion("0.1.0", "v0.2.0")).toBe("0.2.0");

    expect(() => resolveNextVersion("0.1.0", "0.1.0")).toThrow(/strictly greater/);
    expect(() => resolveNextVersion("0.2.0", "0.1.9")).toThrow(/strictly greater/);
  });

  test("reads, validates, and updates all 5 manifest and lockfiles without altering dependency versions", () => {
    const dir = createFixtureRepo("0.1.0");
    expect(assertConsistentVersions(dir)).toBe("0.1.0");

    const updated = updateAllVersions("0.2.0", dir);
    expect(updated).toBe("0.2.0");
    expect(assertConsistentVersions(dir)).toBe("0.2.0");

    expect(readAllVersions(dir)).toEqual({
      "package.json": "0.2.0",
      "package-lock.json#version": "0.2.0",
      'package-lock.json#packages[""].version': "0.2.0",
      "src-tauri/tauri.conf.json": "0.2.0",
      "src-tauri/Cargo.toml": "0.2.0",
      "src-tauri/Cargo.lock": "0.2.0",
    });

    const lockRaw = readFileSync(join(dir, "src-tauri/Cargo.lock"), "utf8");
    expect(lockRaw).toContain('name = "zlib"\nversion = "0.1.0"');
    expect(lockRaw).toContain('name = "serde"\nversion = "1.0.200"');

    const npmLock = JSON.parse(readFileSync(join(dir, "package-lock.json"), "utf8")) as {
      packages: Record<string, { version: string }>;
    };
    expect(npmLock.packages["node_modules/vite"]?.version).toBe("8.3.8");
  });

  test("assertConsistentVersions fails loudly when any lockfile drifts", () => {
    const dir = createFixtureRepo("0.1.0");
    const lockPath = join(dir, "src-tauri/Cargo.lock");
    writeFileSync(
      lockPath,
      readFileSync(lockPath, "utf8").replace(
        'name = "waypoint"\nversion = "0.1.0"',
        'name = "waypoint"\nversion = "0.0.9"',
      ),
      "utf8",
    );

    expect(() => assertConsistentVersions(dir)).toThrow(/Manifest\/lockfile version mismatch/);
  });
});
